"""Shared fixtures for the documentation-tooling tests in `scripts/`.

Not a test suite. The `test-docs-*.py` files import it for the policy loader and
for throwaway Git repositories holding a fixture documentation tree, so each
suite stages and commits real index states instead of simulating them.
"""

import copy
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

import docs_policy

SCRIPTS = Path(__file__).resolve().parent
REPO_ROOT = SCRIPTS.parent
POLICY_PATH = "scripts/docs-policy.json"
ENTRY_POINT = SCRIPTS / "docs.py"

# The generated-index marker both index suites compare against, stated once.
MARKER = ("<!-- Generated by scripts/docs.py from document frontmatter. "
          "Do not edit by hand. -->")


def load_policy():
    """This repository's effective policy: the tracked policy plus its overlay.

    The overlay holds the entries only this private tree can satisfy, so a tree
    without one reads exactly as the exported policy does.
    """
    policy = json.loads((REPO_ROOT / POLICY_PATH).read_text(encoding="utf-8"))
    overlay = REPO_ROOT / docs_policy.PRIVATE_POLICY_PATH
    return docs_policy.merge_policy_overlay(
        policy, json.loads(overlay.read_text(encoding="utf-8")) if overlay.is_file() else None)


# Fixture trees hold only the research group, so their base policy activates just
# that group. A rollout slice that activates another directory in the shipped
# policy must not change what a fixture-based test exercises.
FIXTURE_ACTIVE_DIRECTORIES = ("docs/research",)


def policy(**changes):
    """The shipped policy with named values replaced, for one fixture."""
    changed = copy.deepcopy(load_policy())
    changed["active_directories"] = list(FIXTURE_ACTIVE_DIRECTORIES)
    # A fixture must classify the directory it writes whether or not this tree's
    # overlay names it, so the group is indexed even in an exported tree.
    changed["indexed_directories"] = list(dict.fromkeys(
        list(changed["indexed_directories"]) + list(FIXTURE_ACTIVE_DIRECTORIES)))
    changed.update(changes)
    return changed


def document(title, summary, keywords, extra=""):
    """A complete ordinary document, for fixture trees."""
    body = "---\n"
    body += "title: %s\n" % title
    body += "summary: %s\n" % summary
    body += "keywords:\n"
    for term in keywords.split():
        body += "  - %s\n" % term
    body += extra
    body += "---\n\n# %s\n\nBody text.\n" % title
    return body


class TempRepository:
    """A throwaway Git repository holding a fixture documentation tree.

    The policy is written inside the fixture at its repository-relative path, so
    `docs.py --root <fixture>` reads it exactly as it reads this repository's.
    """

    def __init__(self, testcase, policy_document=None):
        holder = tempfile.TemporaryDirectory()
        testcase.addCleanup(holder.cleanup)
        self.root = Path(holder.name)
        self.env = os.environ.copy()
        for key in ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE", "GIT_COMMON_DIR"):
            self.env.pop(key, None)
        self.git("init", "-q")
        self.git("config", "user.name", "Test")
        self.git("config", "user.email", "test@example.org")
        self.git("config", "core.autocrlf", "false")
        self.write_policy(policy_document or policy())

    def git(self, *args, check=True):
        return subprocess.run(["git", *args], cwd=self.root, env=self.env, check=check,
                              capture_output=True, text=True).stdout

    def write(self, name, text):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))

    def read(self, name):
        return (self.root / name).read_bytes()

    def exists(self, name):
        return (self.root / name).exists()

    def remove(self, name):
        (self.root / name).unlink()

    def write_policy(self, document):
        self.write(POLICY_PATH, json.dumps(document, indent=2) + "\n")

    def commit(self, message="fixture"):
        self.git("add", "-A")
        self.git("commit", "-qm", message)

    def tree_state(self):
        """Every file outside `.git`, by path, so a test can prove nothing moved."""
        state = {}
        for path in sorted(self.root.rglob("*")):
            if path.is_file() and ".git" not in path.parts:
                state[path.relative_to(self.root).as_posix()] = path.read_bytes()
        return state

    def run(self, *args):
        return run_entry(self.root, *args, env=self.env)

    def generate(self, *args):
        return self.run("generate", *args)

    def check(self, *args):
        return self.run("check", *args)

    def coverage(self, *args):
        return self.run("coverage", *args)


def run_entry(root, *args, env=None):
    """Invoke `scripts/docs.py` against `root`, as a user would from that tree."""
    return subprocess.run(
        [sys.executable, str(ENTRY_POINT), *args, "--root", str(root)],
        cwd=root, env=env, capture_output=True, text=True,
    )
