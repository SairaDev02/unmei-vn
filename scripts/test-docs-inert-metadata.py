#!/usr/bin/env python3
"""Generated metadata reaches the index as visible words, not as markup or links.

`docs.py generate` is the seam: the fixture holds valid frontmatter whose title,
summary and status contain Markdown constructs, a bare URL, a bare `www.` domain,
an email address and raw HTML, and the test compares the written index byte for
byte with the expected inert rendering.

Generated bytes are not renderer proof. Whether GitHub's repository-file renderer
shows those bytes as inert text is checked against the real renderer at the
candidate revision, not here.
"""

import unittest

import docs_test_support as support

ADVERSARIAL_TITLE = "Notes [release](https://example.com) *em* <b>bold</b>"
ADVERSARIAL_SUMMARY = ("See https://example.com/a?b=1 and user@example.net; "
                       "www.example.org/path is bare text.")
ADVERSARIAL_STATUS = "[Review](https://example.com) <img src=x> **accepted**"


def quoted_document(title, summary, keywords, status):
    """A valid fixture document; every double-quoted value may hold `:` and `[]`."""
    body = "---\n"
    body += 'title: "%s"\n' % title
    body += 'summary: "%s"\n' % summary
    body += "keywords:\n"
    for term in keywords.split():
        body += "  - %s\n" % term
    body += 'status: "%s"\n' % status
    body += "---\n\n# Documented title\n\nBody text.\n"
    return body


class InertMetadataGenerationTests(unittest.TestCase):
    def setUp(self):
        self.repo = support.TempRepository(
            self, support.policy(active_directories=["docs/adr"],
                                 status_display_directories=["docs/adr"]))
        self.repo.write("docs/adr/0001-metadata.md", quoted_document(
            ADVERSARIAL_TITLE, ADVERSARIAL_SUMMARY, "prototype", ADVERSARIAL_STATUS))
        self.repo.write("docs/adr/0002-alpha.md", support.document(
            "Alpha", "A fixture record.", "prototype", "status: accepted\n"))
        self.repo.commit()

    def test_adversarial_metadata_generates_inert_display_text(self):
        result = self.repo.generate()
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        expected = (
            support.MARKER + "\n"
            "\n"
            "# Index: docs/adr/\n"
            "\n"
            "Generated discovery index. Edit a document's frontmatter, then run\n"
            "`python scripts/docs.py generate`.\n"
            "\n"
            "- [Notes \\[release\\](https://example.com) \\*em\\* \\<b\\>bold\\</b\\>]"
            "(0001-metadata.md) — "
            "See https<!-- -->://example.com/a?b=1 and user<!-- -->@example.net; "
            "www<!-- -->.example.org/path is bare text. "
            "(`prototype`) · status: "
            "\\[Review\\](https<!-- -->://example.com) \\<img src=x\\> "
            "\\*\\*accepted\\*\\*\n"
            "- [Alpha](0002-alpha.md) — A fixture record. "
            "(`prototype`) · status: accepted\n"
        )
        self.assertEqual(self.repo.read("docs/adr/INDEX.md").decode("utf-8"), expected)


if __name__ == "__main__":
    unittest.main()
