class DocumentLifecycleTests(EntryPointCase):
    def test_a_deleted_document_disappears_from_the_index(self):
        self.assertPasses(self.repo.generate())
        self.assertIn(b"0002-b.md", self.repo.read("docs/pages/INDEX.md"))
        self.repo.git("rm", "-q", "docs/pages/0002-b.md")
        self.assertPasses(self.repo.generate())
        self.assertNotIn(b"0002-b.md", self.repo.read("docs/pages/INDEX.md"))
        self.assertPasses(self.repo.check())

    def test_a_renamed_document_replaces_its_entry(self):
        self.assertPasses(self.repo.generate())
        self.repo.git("mv", "docs/pages/0002-b.md", "docs/pages/0003-c.md")
        self.assertFails(self.repo.check(), "docs/pages/INDEX.md", "generate")
        self.assertPasses(self.repo.generate())
        index = self.repo.read("docs/pages/INDEX.md")
        self.assertNotIn(b"0002-b.md", index)
        self.assertIn(b"0003-c.md", index)
        self.assertPasses(self.repo.check())


class StagedSnapshotTests(EntryPointCase):
    def setUp(self):
        super().setUp()
        self.assertPasses(self.repo.generate())
        self.repo.commit("index")

    def test_a_staged_metadata_edit_is_validated_as_staged(self):
        self.repo.write("docs/pages/0001-a.md", valid("Alpha", summary="The staged record."))
        self.repo.git("add", "docs/pages/0001-a.md")
        self.repo.write("docs/pages/0001-a.md", valid("Alpha", summary="An unstaged record."))

        self.assertFails(self.repo.check("--staged"), "docs/pages/INDEX.md", "generate")
        self.assertPasses(self.repo.generate("--staged"))
        self.assertIn(b"The staged record.", self.repo.read("docs/pages/INDEX.md"))
        self.repo.git("add", "docs/pages/INDEX.md")
        self.assertPasses(self.repo.check("--staged"))
        self.assertFails(self.repo.check(), "docs/pages/INDEX.md", "generate")

    def test_a_partially_staged_file_is_read_at_the_staged_content(self):
        self.repo.write("docs/pages/0001-a.md", valid("Alpha", summary="The staged record."))
        self.repo.git("add", "docs/pages/0001-a.md")
        self.repo.write("docs/pages/0001-a.md",
                        valid("Alpha", summary="The staged record.", extra="owner: someone\n"))

        self.assertPasses(self.repo.generate("--staged"))
        self.repo.git("add", "docs/pages/INDEX.md")
        self.assertPasses(self.repo.check("--staged"))
        self.assertFails(self.repo.check(), "docs/pages/0001-a.md", "remove 'owner'")

    def test_a_staged_rename_is_reported_and_then_resolved(self):
        self.repo.git("mv", "docs/pages/0002-b.md", "docs/pages/0003-c.md")
        before = self.repo.read("docs/pages/INDEX.md")
        self.assertFails(self.repo.check("--staged"), "docs/pages/INDEX.md", "generate")
        self.assertEqual(self.repo.read("docs/pages/INDEX.md"), before)
        self.assertPasses(self.repo.generate("--staged"))
        self.repo.git("add", "docs/pages/INDEX.md")
        self.assertPasses(self.repo.check("--staged"))
        self.assertNotIn(b"0002-b.md", self.repo.read("docs/pages/INDEX.md"))

    def test_a_staged_deletion_is_reported_and_then_resolved(self):
        self.repo.git("rm", "-q", "docs/pages/0002-b.md")
        before = self.repo.read("docs/pages/INDEX.md")
        self.assertFails(self.repo.check("--staged"), "docs/pages/INDEX.md", "generate")
        self.assertEqual(self.repo.read("docs/pages/INDEX.md"), before)
        self.assertPasses(self.repo.generate("--staged"))
        self.repo.git("add", "docs/pages/INDEX.md")
        self.assertPasses(self.repo.check("--staged"))

    def test_the_staged_check_reads_the_staged_policy(self):
        looser = fixture_policy()
        looser["keyword_allowlist"].append("experimental")
        self.repo.write_policy(looser)
        self.assertPasses(self.repo.generate())
        self.repo.write("docs/pages/0001-a.md", valid("Alpha", keywords="experimental"))
        self.assertPasses(self.repo.generate())
        self.assertPasses(self.repo.check())

        tighter = fixture_policy()
        self.repo.write_policy(tighter)
        self.repo.git("add", support.POLICY_PATH, "docs/pages/INDEX.md",
                      "docs/pages/0001-a.md")
        self.repo.write_policy(looser)
        self.assertFails(self.repo.check("--staged"), "docs/pages/0001-a.md",
                         "replace 'experimental'")
        self.assertPasses(self.repo.check())

    def test_the_staged_check_ignores_the_worktree_index_copy(self):
        self.repo.write("docs/pages/0001-a.md", valid("Alpha", summary="A worktree edit."))
        self.assertFails(self.repo.check(), "docs/pages/INDEX.md", "generate")
        self.assertPasses(self.repo.check("--staged"))


