class ToolErrorTests(EntryPointCase):
    def test_a_directory_that_is_not_a_repository_is_a_tool_error(self):
        holder = tempfile.TemporaryDirectory()
        self.addCleanup(holder.cleanup)
        root = Path(holder.name)
        policy = support.REPO_ROOT / support.POLICY_PATH
        (root / "scripts").mkdir()
        (root / support.POLICY_PATH).write_bytes(policy.read_bytes())
        self.assertToolError(support.run_entry(root, "check", env=self.repo.env), "docs:")

    def test_an_unmerged_index_is_a_tool_error(self):
        self.repo.write("docs/pages/0001-a.md", "base\n")
        self.repo.commit("base")
        self.repo.git("checkout", "-q", "-b", "other")
        self.repo.write("docs/pages/0001-a.md", "other\n")
        self.repo.commit("other")
        self.repo.git("checkout", "-q", "-")
        self.repo.write("docs/pages/0001-a.md", "main\n")
        self.repo.commit("main")
        self.repo.git("merge", "other", check=False)
        self.assertToolError(self.repo.check("--staged"), "unmerged")

    def test_an_unknown_revision_is_a_tool_error(self):
        self.assertToolError(self.repo.check("--checkout", "--rev", "no-such-branch"),
                             "docs:")

    def test_an_unreadable_policy_is_a_tool_error(self):
        self.repo.write(support.POLICY_PATH, "{ not json")
        self.assertToolError(self.repo.check(), "docs:")

    def test_a_duplicate_evidence_root_is_a_policy_error(self):
        """The rule is one root registered twice, so the fixture registers its own twice."""
        broken = support.load_policy()
        roots = broken["classifications"].setdefault("evidence_roots", [])
        roots.extend([FIXTURE_EVIDENCE_ROOT, FIXTURE_EVIDENCE_ROOT])
        self.repo.write_policy(broken)
        result = self.repo.check()
        self.assertToolError(result, "registered twice")

    def test_a_policy_missing_a_core_key_stops_check_and_coverage(self):
        """The core commands own this key set; a missing key stops them before a verdict."""
        broken = fixture_policy()
        del broken["keyword_allowlist"]
        self.repo.write_policy(broken)
        for command in ("check", "coverage"):
            with self.subTest(command=command):
                self.assertToolError(self.repo.run(command),
                                     "%s is missing keyword_allowlist" % support.POLICY_PATH)


def coverage_counts(result):
    """`coverage` prints one `<class> <count>` line per class; parse them back."""
    counts = {}
    for line in result.stdout.splitlines():
        fields = line.split()
        if len(fields) == 2 and fields[1].isdigit():
            counts[fields[0]] = int(fields[1])
    return counts


