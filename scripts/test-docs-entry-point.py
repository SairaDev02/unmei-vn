#!/usr/bin/env python3
"""The entry point validates a candidate snapshot and reports coverage.

Each test breaks one hard rule, stages one change, or reads one snapshot, then
asserts the exit status, the path named by the diagnostic, and the remedy it
states. Exit 0 is success, 1 is findings, 2 is a tool error.
"""

import os
import subprocess
import tempfile
import unittest
from pathlib import Path

import docs_test_support as support


# The fixtures write into a synthetic root that the fixture policy declares and
# indexes itself, so no case depends on a directory only this private tree owns.
FIXTURE_DIRECTORY = "docs/pages"

# A synthetic evidence root, registered twice by the one case that proves a
# duplicate root is a policy error.
FIXTURE_EVIDENCE_ROOT = "docs/fixture-receipts"


def fixture_policy(**changes):
    """The fixture policy: the shipped one, with the fixture root made active.

    The other indexed directories stay, so a case can still exercise a directory
    outside the active set.
    """
    document = support.policy()
    document["active_directories"] = [FIXTURE_DIRECTORY]
    document["indexed_directories"] = list(dict.fromkeys(
        list(document["indexed_directories"]) + [FIXTURE_DIRECTORY]))
    document.update(changes)
    return document


def valid(title, summary="A fixture record.", keywords="prototype", extra=""):
    return support.document(title, summary, keywords, extra)


class EntryPointCase(unittest.TestCase):
    def setUp(self):
        self.repo = support.TempRepository(self, fixture_policy())
        self.repo.write("README.md", "# Readme\n")
        self.repo.write("docs/pages/0001-a.md", valid("Alpha"))
        self.repo.write("docs/pages/0002-b.md", valid("Beta"))
        self.repo.commit()

    def assertFails(self, result, path, remedy):
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn(path, result.stderr)
        self.assertIn("fix:", result.stderr)
        self.assertIn(remedy, result.stderr)

    def assertPasses(self, result):
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)

    def assertToolError(self, result, message):
        self.assertEqual(result.returncode, 2, result.stdout + result.stderr)
        self.assertIn(message, result.stderr)
        self.assertNotIn("fix:", result.stderr)


class GenerateAndCheckTests(EntryPointCase):
    def test_generate_writes_the_index_and_check_accepts_it(self):
        self.assertPasses(self.repo.generate())
        index = self.repo.read("docs/pages/INDEX.md").decode("utf-8")
        self.assertTrue(index.startswith("<!-- Generated by scripts/docs.py"))
        self.assertIn("- [Alpha](0001-a.md) — A fixture record. (`prototype`)", index)
        self.assertPasses(self.repo.check())

    def test_repeated_generation_is_byte_identical(self):
        self.assertPasses(self.repo.generate())
        first = self.repo.read("docs/pages/INDEX.md")
        self.assertPasses(self.repo.generate())
        self.assertEqual(self.repo.read("docs/pages/INDEX.md"), first)
        self.repo.commit("index")
        self.assertPasses(self.repo.generate())
        self.assertEqual(self.repo.git("status", "--porcelain"), "")

    def test_generate_writes_only_the_active_directories_index(self):
        before = set(self.repo.tree_state())
        self.assertPasses(self.repo.generate())
        self.assertEqual(set(self.repo.tree_state()) - before, {"docs/pages/INDEX.md"})

    def test_a_failed_generate_writes_nothing(self):
        self.repo.write("docs/pages/0001-a.md", valid("Alpha", extra="owner: someone\n"))
        before = self.repo.tree_state()
        self.assertEqual(self.repo.generate().returncode, 1)
        self.assertEqual(self.repo.tree_state(), before)
        self.assertFalse(self.repo.exists("docs/pages/INDEX.md"))

    def test_a_stale_index_fails_with_the_regeneration_command(self):
        self.assertPasses(self.repo.generate())
        self.repo.write("docs/pages/0001-a.md", valid("Alpha", summary="A changed record."))
        self.assertFails(self.repo.check(), "docs/pages/INDEX.md",
                         "python scripts/docs.py generate && git add docs/pages/INDEX.md")

    def test_a_missing_index_fails_with_the_regeneration_command(self):
        self.assertFails(self.repo.check(), "docs/pages/INDEX.md",
                         "python scripts/docs.py generate")

    def test_check_never_writes(self):
        self.repo.write("prototype/276/README.md", "# stray\n")
        self.repo.git("add", "prototype/276/README.md")
        before = self.repo.tree_state()
        self.assertEqual(self.repo.check().returncode, 1)
        self.assertEqual(self.repo.tree_state(), before)

    def test_an_index_with_crlf_line_endings_is_stale(self):
        """The indexes are pinned to LF, so the comparison is byte-exact."""
        self.assertPasses(self.repo.generate())
        text = self.repo.read("docs/pages/INDEX.md").decode("utf-8")
        self.repo.write("docs/pages/INDEX.md", text.replace("\n", "\r\n"))
        self.assertFails(self.repo.check(), "docs/pages/INDEX.md", "generate")
        self.assertPasses(self.repo.generate())
        self.assertNotIn(b"\r", self.repo.read("docs/pages/INDEX.md"))
        self.assertPasses(self.repo.check())


class MetadataRuleTests(EntryPointCase):
    def test_unknown_field(self):
        self.repo.write("docs/pages/0001-a.md", valid("Alpha", extra="owner: someone\n"))
        self.assertFails(self.repo.check(), "docs/pages/0001-a.md", "remove 'owner'")

    def test_missing_required_field(self):
        self.repo.write("docs/pages/0001-a.md",
                        "---\ntitle: Alpha\nkeywords:\n  - prototype\n---\n\n# Alpha\n")
        self.assertFails(self.repo.check(), "docs/pages/0001-a.md", "add 'summary:")

    def test_empty_keyword_list(self):
        self.repo.write("docs/pages/0001-a.md",
                        "---\ntitle: Alpha\nsummary: A record.\nkeywords: []\n---\n\n# Alpha\n")
        self.assertFails(self.repo.check(), "docs/pages/0001-a.md", "1-8 approved keywords")

    def test_duplicate_keyword(self):
        self.repo.write("docs/pages/0001-a.md", valid("Alpha", keywords="prototype prototype"))
        self.assertFails(self.repo.check(), "docs/pages/0001-a.md",
                         "remove the duplicated term")

    def test_unapproved_keyword(self):
        self.repo.write("docs/pages/0001-a.md", valid("Alpha", keywords="prototype experimental"))
        self.assertFails(self.repo.check(), "docs/pages/0001-a.md",
                         "replace 'experimental' with a term from " + support.POLICY_PATH)

    def test_missing_frontmatter(self):
        self.repo.write("docs/pages/0001-a.md", "# Alpha\n\nNo metadata.\n")
        self.assertFails(self.repo.check(), "docs/pages/0001-a.md",
                         "start the file with a `---` line")

    def test_a_summary_over_the_limit(self):
        self.repo.write("docs/pages/0001-a.md", valid("Alpha", summary="x" * 161))
        self.assertFails(self.repo.check(), "docs/pages/0001-a.md", "at most 160 characters")

    def test_bad_local_reference(self):
        self.repo.write("docs/pages/0001-a.md", valid("Alpha", extra="related:\n  - ./missing.md\n"))
        self.assertFails(self.repo.check(), "docs/pages/0001-a.md",
                         "point 'related' at a file or directory in the candidate tree")

    def test_a_reference_that_escapes_the_repository(self):
        self.repo.write("docs/pages/0001-a.md",
                        valid("Alpha", extra="related:\n  - ../../../outside.md\n"))
        self.assertFails(self.repo.check(), "docs/pages/0001-a.md", "stays inside the repository")

    def test_metadata_in_a_directory_outside_the_active_ones_is_not_validated(self):
        """Classification is whole-tree; metadata enforcement is the fixture's active set."""
        self.repo.write("docs/adr/0001-plain.md", "# Plain ADR\n\nNo metadata at all.\n")
        self.repo.commit()
        self.assertPasses(self.repo.generate())
        self.assertPasses(self.repo.check())
        self.assertFalse(self.repo.exists("docs/adr/INDEX.md"))
        counts = coverage_counts(self.repo.coverage())
        self.assertEqual(counts["ordinary"], 3)
        self.assertEqual(counts["root-guidance"], 1)


