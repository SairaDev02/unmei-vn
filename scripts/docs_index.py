"""Deterministic rendering of a generated directory index.

An index is a projection of its direct documents' metadata, never a second
source of authority: nothing from a document body reaches it.

The output is UTF-8 with LF endings only. `.gitattributes` pins the four index
paths to `eol=lf`, so the generator, the checkout and the validator agree on the
bytes; the checker compares them exactly rather than normalising line endings.
"""

import posixpath
import string
from typing import NamedTuple

# Markdown link syntax is not URL syntax: `?` and `#` start a query or fragment,
# and `(` `)` close the destination early, so a literal file name must encode
# them. The same table is applied to fragments, which are configured without `#`.
TARGET_ESCAPES = {
    "%": "%25", " ": "%20", "(": "%28", ")": "%29", "#": "%23", "?": "%3F",
    "<": "%3C", ">": "%3E", "[": "%5B", "]": "%5D",
}

# The schema allows display text that looks like Markdown, so every character
# that can open or close an inline construct is escaped: a title, summary or
# status containing a link, emphasis, code or raw HTML must render as prose, not
# as a second navigation surface. Keywords are allowlisted lowercase ASCII and
# stay in inline code, which is why they need no escaping.
INLINE_ESCAPES = {
    char: "\\" + char for char in "\\`*_[]<>|~&"
}

# No backslash escape stops a GFM autolink, but an empty HTML comment does: the
# autolinker needs one text node, and a comment splits it at the connector
# character. The comment renders as nothing, so the reader still sees the words
# as the author wrote them. `www.` takes the comment before the dot; after it,
# the renderer links a bare `www`.
AUTOLINK_BREAK = "<!-- -->"
AUTOLINK_LOCAL_CHARS = frozenset(string.ascii_letters + string.digits + ".+-_")
AUTOLINK_DOMAIN_CHARS = frozenset(string.ascii_letters + string.digits + "-_")


class Document(NamedTuple):
    path: str
    title: str
    summary: str
    keywords: list
    status: str | None = None


def escape_target(value):
    return "".join(TARGET_ESCAPES.get(ch, ch) for ch in value)


def escape_inline(value):
    """Escaping for text that renders inside a Markdown link, such as a title.

    GFM autolinks nothing inside link text, so a URL or address there keeps only
    the Markdown escapes and its bytes stay as they were.
    """
    return "".join(INLINE_ESCAPES.get(char, char) for char in value)


def autolink_connector_indices(value):
    """The indices to split at so no autolink can form: `scheme://`, `www.`, `local@domain`.

    A deliberately conservative superset of what GitHub's repository-file
    renderer links today, because the autolink pattern is the renderer's, not
    ours: an unmarked connector risks a live link, while a marked one the
    renderer never linked is an invisible comment.
    """
    points = set()
    for index, char in enumerate(value):
        if char == ":" and value.startswith("//", index + 1):
            points.add(index)
        elif char == "." and value[max(0, index - 3):index].lower() == "www":
            points.add(index)
        elif char == "@" and 0 < index < len(value) - 1 \
                and value[index - 1] in AUTOLINK_LOCAL_CHARS \
                and value[index + 1] in AUTOLINK_DOMAIN_CHARS:
            points.add(index)
    return points


def escape_display_text(value):
    """Escaping for frontmatter text that renders as prose, not inside a link."""
    pieces = []
    start = 0
    for index in sorted(autolink_connector_indices(value)):
        pieces.append(escape_inline(value[start:index]))
        pieces.append(AUTOLINK_BREAK)
        start = index
    pieces.append(escape_inline(value[start:]))
    return "".join(pieces)


def entry_line(document, policy):
    line = "- [%s](%s) — %s" % (
        escape_inline(document.title),
        escape_target(posixpath.basename(document.path)),
        escape_display_text(document.summary),
    )
    line += " (%s)" % ", ".join("`%s`" % term for term in document.keywords)
    if document.status is not None and posixpath.dirname(document.path) in \
            policy["status_display_directories"]:
        line += " · status: %s" % escape_display_text(document.status)
    return line


def render(directory, documents, child_directories, policy):
    """The expected bytes of `<directory>/<index_name>` for these documents."""
    index_name = policy["index_name"]
    lines = [
        "<!-- Generated by %s from document frontmatter. Do not edit by hand. -->"
        % policy["entry_point"],
        "",
        "# Index: %s/" % directory,
        "",
        "Generated discovery index. Edit a document's frontmatter, then run",
        "`%s`." % policy["generate_command"],
    ]

    entries = []
    ordered = sorted(documents, key=lambda document: document.path)
    for document in ordered:
        parent = posixpath.dirname(document.path)
        if posixpath.basename(document.path) == index_name:
            continue
        if parent != directory:
            raise ValueError("%s is not a direct document of %s" % (document.path, directory))
        entries.append(entry_line(document, policy))
        for link in policy["section_links"].get(document.path, []):
            entries.append("  - [%s](%s#%s)" % (
                escape_inline(link["label"]),
                escape_target(posixpath.basename(document.path)),
                escape_target(link["fragment"]),
            ))
    # A directory whose pages have not landed yet renders its header alone, so the
    # blank separator belongs to the entries rather than to the header.
    if entries:
        lines.append("")
        lines.extend(entries)

    children = sorted(child_directories)
    if children:
        lines.extend(["", "## Child directories", ""])
        for child in children:
            target = posixpath.relpath(child + "/" + index_name, directory)
            lines.append("- [`%s/`](%s)" % (child, escape_target(target)))

    landing = policy["excluded_landing_links"].get(directory + "/" + index_name)
    if landing:
        lines.extend(["", "## Related", ""])
        for link in landing:
            lines.append("- [%s](%s)" % (escape_inline(link["label"]),
                                          escape_target(link["target"])))

    return ("\n".join(lines) + "\n").encode("utf-8")
